#!/usr/bin/env node
// Writes the dApp for one environment (#43): a copy of web/ in which only two things differ,
// assets/network.js (from networks/<env>.json) and the connect-src of the CSP in _headers (that
// environment's RPC). Everything else is byte-for-byte what ships. web/ itself is the sepolia
// build, committed: test/web/network.test.cjs requires `sepolia` to reproduce it exactly.
//
//   node scripts/web-env.cjs <sepolia|local|mainnet> <outDir> [--rpc-url <url>]
//
// --rpc-url overrides the RPC for `local` only (the e2e stack's host port is configurable).
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const WEB = path.join(ROOT, 'web');
const KEYS = ['name', 'chainId', 'chainName', 'rpcUrl', 'explorer', 'explorerName', 'registry', 'collateral'];
// Base mainnet, keyed on the chain as script/DeployCopraMainnet.s.sol's BASE_CHAIN_ID is: whatever a
// settings file is named, a page on chain 8453 talks to the contracts deployed against real USDC.
const BASE_CHAIN_ID = 8453;

function loadNetwork(env, { rpcUrl } = {}) {
  const file = path.join(ROOT, 'networks', `${path.basename(env)}.json`);
  if (!fs.existsSync(file)) throw new Error(`no network settings for '${env}' (${file})`);
  const net = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (rpcUrl) {
    if (net.name !== 'local') throw new Error('--rpc-url is for the local environment only');
    net.rpcUrl = rpcUrl;
  }
  validate(net);
  // Canonical key order, so network.js does not depend on how the settings file is ordered.
  return Object.fromEntries(KEYS.map((k) => [k, net[k]]));
}

function validate(net) {
  const keys = Object.keys(net);
  if (keys.length !== KEYS.length || !KEYS.every((k) => keys.includes(k))) throw new Error(`network settings must have exactly ${KEYS.join(', ')}; got ${keys.join(', ')}`);
  if (!Number.isSafeInteger(net.chainId) || net.chainId <= 0) throw new Error(`chainId ${net.chainId}`);
  // null: no CopraRegistry on that network yet. The settings load, but no site is built for it.
  if (net.registry !== null && !/^0x[0-9a-fA-F]{40}$/.test(net.registry)) throw new Error(`registry ${net.registry}`);
  if (!/^https?:$/.test(new URL(net.rpcUrl).protocol)) throw new Error(`rpcUrl ${net.rpcUrl}`);
  // Only a local chain may be plain http; a public network's RPC and explorer must be https.
  if (net.name !== 'local' && !net.rpcUrl.startsWith('https://')) throw new Error(`rpcUrl must be https: ${net.rpcUrl}`);
  if (net.explorer !== null && !net.explorer.startsWith('https://')) throw new Error(`explorer must be https or null: ${net.explorer}`);
  // The name the page gives its explorer links ("View on Basescan"): present exactly when there is one.
  if (net.explorer === null ? net.explorerName !== null : !(typeof net.explorerName === 'string' && net.explorerName.trim())) {
    throw new Error(`explorerName must name the explorer, or be null without one: ${net.explorerName}`);
  }
  // The collateral the network's contract set uses: TestnetUSDC (with its public faucet) or Circle's USDC.
  // Base mainnet takes only USDC, as script/DeployCopraMainnet.s.sol does (#47).
  if (!['TestnetUSDC', 'USDC'].includes(net.collateral)) throw new Error(`collateral must be TestnetUSDC or USDC: ${net.collateral}`);
  if (net.chainId === BASE_CHAIN_ID && net.collateral !== 'USDC') throw new Error(`collateral must be USDC on Base mainnet (${BASE_CHAIN_ID})`);
}

function networkJs(net) {
  return `// Network settings for the "${net.name}" environment (#43). Generated by scripts/web-env.cjs from
// networks/${net.name}.json: edit that file and regenerate, never this one.
// Classic script, loaded before config.js; it only declares.
const NETWORK = Object.freeze(${JSON.stringify(net, null, 2)});
`;
}

/** web/_headers with connect-src set to 'self' and this network's RPC origin; nothing else changes. */
function headersFor(net, headers) {
  let replaced = 0;
  const out = headers.replace(/connect-src [^;\n]*/g, () => {
    replaced++;
    return `connect-src 'self' ${new URL(net.rpcUrl).origin}`;
  });
  if (replaced !== 1) throw new Error(`expected one connect-src in web/_headers, found ${replaced}`);
  return out;
}

function build(env, outDir, opts = {}) {
  const net = loadNetwork(env, opts);
  if (net.registry === null) throw new Error(`no CopraRegistry on ${net.name} yet: set its registry in networks/${net.name}.json once deployed`);
  const out = path.resolve(outDir);
  if (out === WEB || out.startsWith(WEB + path.sep)) throw new Error('outDir must not be inside web/');
  fs.rmSync(out, { recursive: true, force: true });
  fs.cpSync(WEB, out, { recursive: true });
  fs.writeFileSync(path.join(out, 'assets', 'network.js'), networkJs(net));
  fs.writeFileSync(path.join(out, '_headers'), headersFor(net, fs.readFileSync(path.join(WEB, '_headers'), 'utf8')));
  return net;
}

module.exports = { loadNetwork, validate, networkJs, headersFor, build };

if (require.main === module) {
  const [env, outDir, flag, rpcUrl] = process.argv.slice(2);
  if (!env || !outDir || (flag && flag !== '--rpc-url') || (flag && !rpcUrl)) {
    console.error('usage: node scripts/web-env.cjs <sepolia|local|mainnet> <outDir> [--rpc-url <url>]');
    process.exit(2);
  }
  const net = build(env, outDir, { rpcUrl });
  console.log(`web/ for ${net.name} (chain ${net.chainId}, RPC ${net.rpcUrl}) written to ${outDir}`);
}
